/**
 * Builds the two consolidated SQL files from the untouched migration sources.
 *
 *   node scripts/db/build-migration-files.mjs
 *
 * Outputs
 *   supabase/ALL_MIGRATIONS.sql      verbatim concatenation, for a FRESH database only
 *   supabase/PENDING_MIGRATIONS.sql  only the migrations still outstanding for the
 *                                    existing database, containing nothing that could
 *                                    fail or duplicate work if already applied
 *
 * The numbered files in supabase/migrations/ remain the source of truth and are never
 * modified by this script. Re-run it whenever a migration is added.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const MIGRATIONS = join(ROOT, "supabase", "migrations");
const OUT_DIR = join(ROOT, "supabase");

/**
 * Migrations confirmed present in the founder's Supabase project on 2026-11-01 by a
 * PostgREST probe (404 PGRST205 = missing, 401 42501 = present):
 *   companion_messages -> 401  => 0008 applied
 *   interventions      -> 401  => 0009 applied
 * 0010 could not be confirmed column-by-column through PostgREST, so it is treated as
 * pending. It is written with `add column if not exists` and `drop constraint if
 * exists`, so running it again cannot damage an already-patched schema.
 */
const APPLIED = ["0001", "0002", "0003", "0004", "0005", "0006", "0007", "0008", "0009"];

/**
 * Migrations that are safe to re-run even if already applied, because every statement
 * either checks for the object or replaces it. Anything NOT in this set is excluded
 * from the pending file rather than risk a duplicate-object error mid-way.
 */
const IDEMPOTENT = ["0010", "0011"];

const files = readdirSync(MIGRATIONS).filter((name) => name.endsWith(".sql")).sort();

const banner = (index, total, name) => `-- ============================================================================
-- ${index}/${total} — ${name}
-- ============================================================================
`;

const header = (body) => `-- ============================================================================
--  NABTA — consolidated migrations
-- ============================================================================
${body}
-- Generated by scripts/db/build-migration-files.mjs. Do not edit by hand.
-- ============================================================================

`;

// ---------------------------------------------------------------- ALL_MIGRATIONS
const allParts = [
  header(`--  WHEN TO USE THIS FILE
--    A brand-new, empty Supabase project. It is every migration, verbatim, in
--    filename order — exactly what running the numbered files one by one would do.
--
--  DO NOT run this against a database that already has the schema: it is not
--    idempotent and will fail with "already exists" part-way through.
--
--  The numbered files in supabase/migrations/ remain the source of truth.
--    This file is a convenience copy.`),
];

files.forEach((name, index) => {
  allParts.push(banner(index + 1, files.length, name));
  allParts.push(readFileSync(join(MIGRATIONS, name), "utf8").trimEnd() + "\n");
});

writeFileSync(join(OUT_DIR, "ALL_MIGRATIONS.sql"), allParts.join("\n"), "utf8");

// ------------------------------------------------------------ PENDING_MIGRATIONS
const pending = files.filter((name) => {
  const id = name.slice(8, 12);
  if (APPLIED.includes(id)) return false;
  return IDEMPOTENT.includes(id);
});

const skippedNotIdempotent = files.filter((name) => {
  const id = name.slice(8, 12);
  return !APPLIED.includes(id) && !IDEMPOTENT.includes(id);
});

const pendingParts = [
  header(`--  WHEN TO USE THIS FILE
--    The existing project at the founder's Supabase instance, which already has
--    migrations ${APPLIED[0]}–${APPLIED[APPLIED.length - 1]} applied.
--
--  HOW THE PENDING LIST WAS DECIDED
--    Not by filename. A read-only PostgREST probe of the live project on 2026-11-01
--    showed:
--      companion_messages  -> 401 42501  (exists)   => 0008 applied
--      interventions       -> 401 42501  (exists)   => 0009 applied
--    Migrations that create objects outright (0009) are therefore EXCLUDED. Running
--    them again would fail on "relation already exists" part-way through and leave a
--    half-applied schema.
--
--  WHAT THIS FILE CONTAINS, AND WHY IT IS SAFE TO RE-RUN
--    Only migrations whose every statement either checks for the object or replaces
--    it, so applying this file twice is harmless:
${pending.map((name) => `--      ${name}`).join("\n") || "--      (nothing pending)"}
--
--  EXCLUDED ON PURPOSE (not idempotent, so never re-run blindly)
${skippedNotIdempotent.map((name) => `--      ${name}`).join("\n") || "--      none"}
--
--  MANUAL REVIEW REQUIRED
--    0011 rewrites an RLS policy ("Students can read assigned lessons"). Whether it
--    is already applied cannot be checked through PostgREST, which is why it is
--    included: it drops the policy if present and recreates it, so it is safe either
--    way. It only narrows nothing and widens nothing — the predicate becomes an
--    explicit outer reference.
--
--  Unverified by this file: existing RLS policies, grants, constraints and triggers
--  are left exactly as they are. Nothing here revokes or weakens a protection.`),
];

pending.forEach((name, index) => {
  pendingParts.push(banner(index + 1, pending.length, name));
  pendingParts.push(readFileSync(join(MIGRATIONS, name), "utf8").trimEnd() + "\n");
});

writeFileSync(join(OUT_DIR, "PENDING_MIGRATIONS.sql"), pendingParts.join("\n"), "utf8");

console.log(`migrations found: ${files.length}`);
console.log(`ALL_MIGRATIONS.sql     <- ${files.length} files, verbatim`);
console.log(`PENDING_MIGRATIONS.sql <- ${pending.length} file(s): ${pending.join(", ") || "none"}`);
console.log(`excluded (applied or not idempotent): ${skippedNotIdempotent.join(", ") || "none"}`);
